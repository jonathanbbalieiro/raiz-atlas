import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import crypto from "node:crypto";
const root=process.cwd();
const ref=JSON.parse(fs.readFileSync(path.join(root,"docs/merge/preserve-original-49.json"),"utf8"));
const sha=x=>crypto.createHash("sha256").update(fs.readFileSync(x)).digest("hex");
const folder=path.join(root,"data/br/parks");
const paths=fs.readdirSync(folder).filter(x=>fs.existsSync(path.join(folder,x,"expedition.json")));
assert.equal(paths.length,75,"O catálogo deve ter 75 expedições");
for(const [slug,hash] of Object.entries(ref)) assert.equal(sha(path.join(folder,slug,"expedition.json")),hash,`Original alterado: ${slug}`);
const newSlugs=JSON.parse(fs.readFileSync(path.join(root,"docs/merge/novas-26.json"),"utf8"));
assert.equal(newSlugs.length,26);
for(const slug of newSlugs) assert(!ref[slug] && paths.includes(slug),`Expedição faltante: ${slug}`);
const parks=JSON.parse(fs.readFileSync(path.join(root,"data/br/parks.generated.json"),"utf8"));
assert.equal(parks.length,77);
assert(fs.existsSync(path.join(root,"src/components/views/ParkQuiz.tsx")));
assert(fs.existsSync(path.join(root,"src/components/views/LostWorld.tsx")));
assert(fs.existsSync(path.join(root,"src/components/views/ReadingProgress.tsx")));
assert(fs.existsSync(path.join(root,"src/components/views/FloraHighlight.tsx")));
assert(fs.existsSync(path.join(root,"src/components/views/PhotoCompare.tsx")));
console.log(`PASSOU — ${parks.length} parques, ${paths.length} Expedições, 49 originais intactas, 26 adicionadas, quiz, mundo perdido, leitura e flora preservados.`);
